  function trimTail(s) {
    return String(s == null ? '' : s).replace(/[\s"'’”`)\]\}>,.:;!?~…·]+$/, '');
  }
  function lastChar(s) {
    var t = trimTail(s);
    return t ? t.charAt(t.length - 1) : '';
  }
  function hasBatchim(ch) {
    if (!ch) return false;
    var c = ch.charCodeAt(0);
    if (c >= 0xAC00 && c <= 0xD7A3) return (c - 0xAC00) % 28 !== 0;
    if (c >= 0x3131 && c <= 0x318E) {
      // 낱자 ㄱ~ㅎ
      return 'ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ'.indexOf(ch) >= 0;
    }
    if (c >= 48 && c <= 57) return '013678'.indexOf(ch) >= 0; // 영·일·삼·육·칠·팔
    if (/[A-Za-z]/.test(ch)) return 'LMP'.indexOf(ch.toUpperCase()) >= 0; // 엘·엠·피
    return false;
  }
  function hasRieul(ch) {
    var c = ch.charCodeAt(0);
    if (c >= 0xAC00 && c <= 0xD7A3) return (c - 0xAC00) % 28 === 8;
    if (c >= 48 && c <= 57) return ch === '7' || ch === '1' || ch === '8';
    return false;
  }
  function josa(word, withB, withoutB) {
    return hasBatchim(lastChar(word)) ? withB : withoutB;
  }
  function josaRo(word) {
    var ch = lastChar(word);
    if (!ch) return '로';
    if (hasBatchim(ch) && !hasRieul(ch)) return '으로';
    return '로';
  }

  /* 토큰 치환: {W} {K} {S}, {K|이/가}, {W|은/는} */
  function render(tpl, ctx) {
    var out = String(tpl).replace(/\{([WKQOACH])\|([^}\/]+)\/([^}]+)\}/g, function (m, key, a, b) {
      var v = ctx[key] || '';
      if (/^(으로|로)$/.test(a)) return v + josaRo(v);
      return v + josa(v, a, b);
    });
    out = out
      .replace(/\{W\}/g, ctx.W || '')
      .replace(/\{K\}/g, ctx.K || '')
      .replace(/\{S\}/g, ctx.S || '')
      .replace(/\{Q\}/g, ctx.Q || '')
      .replace(/\{O\}/g, ctx.O || '')
      .replace(/\{C\}/g, ctx.C || '')
      .replace(/\{A\}/g, ctx.A || '')
      .replace(/\{H\}/g, ctx.H || '');
    return tidy(out);
  }
  function tidy(s) {
    return String(s == null ? '' : s)
      .replace(/\s+/g, ' ')
      .replace(/\s+([,.!?])/g, '$1')
      .replace(/[({\[]\s+/g, function (m) { return m.charAt(0); })
      .replace(/\s+[)\}\]]/g, function (m) { return m.charAt(m.length - 1); })
      .trim();
  }

  function charLen(s) { return String(s).length; }
  /* 달래쨘 실제 제목이 35~45자대라, '적정' 구간을 그에 맞춥니다 */
  function fitOf(len) {
    if (len >= 24 && len <= 45) return { cls: 'good', label: '적정' };
    if (len < 24) return { cls: 'short', label: '짧음' };
    if (len <= 55) return { cls: 'long', label: '김' };
    return { cls: 'long', label: '너무 김' };
  }

  function findAggro(text) {
    var t = String(text || '');
    var hit = [];
    for (var i = 0; i < AGGRO_WORDS.length; i++) {
      if (t.indexOf(AGGRO_WORDS[i]) !== -1) hit.push(AGGRO_WORDS[i]);
    }
    return hit;
  }
  /* 작품명 지우기 (과거작 모드) */
  function stripWork(text, work) {
    var w = tidy(work);
    var t = tidy(text);
    if (!w || w.length < 2) return t;
    var out = t.split(w).join(' ');
    return tidy(out).replace(/^[,·:：\-\s]+/, '');
  }
  function containsWork(text, work) {
    var w = tidy(work);
    return w.length >= 2 && String(text).indexOf(w) !== -1;
  }
  function soften(text) {
    var out = String(text || '');
    for (var i = 0; i < AGGRO_WORDS.length; i++) {
      var w = AGGRO_WORDS[i];
      if (out.indexOf(w) !== -1) out = out.split(w).join(SOFTEN[w] || '');
    }
    return tidy(out);
  }

  function getCategory(id) {
    for (var i = 0; i < CATEGORIES.length; i++) if (CATEGORIES[i].id === id) return CATEGORIES[i];
    return CATEGORIES[0];
  }

