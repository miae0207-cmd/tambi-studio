  function buildAngles(catId, work, keyword, rot, mode) {
    var cat = getCategory(catId);
    var W = tidy(work) || '이 작품';
    var K = tidy(keyword) || cat.defKey;
    var hide = mode === 'hide';
    var r = ((rot || 0) % 3 + 3) % 3;
    var ctx = { W: W, K: K, S: K };
    var ctxHide = { W: '', K: K, S: K };
    var out = [];
    for (var i = 0; i < cat.angles.length; i++) {
      var a = cat.angles[i];
      var samples = [];
      if (hide) {
        var hooks = HIDE_SAMPLES[a.n];
        if (hooks && hooks.length) {
          for (var hi = 0; hi < Math.min(2, hooks.length); hi++) {
            samples.push(render(hooks[(hi + r) % hooks.length], ctxHide));
          }
        } else {
          for (var hj = 0; hj < 2; hj++) samples.push(stripWork(render(a.s[hj], ctx), W));
        }
      } else {
        for (var j = 0; j < 2; j++) {
          var tpl = a.s[(j + r) % a.s.length];
          samples.push(render(tpl, ctx));
        }
      }
      var guide = [];
      for (var gi = 0; gi < a.g.length; gi++) guide.push(render(a.g[gi], ctx));
      out.push({
        key: cat.id + '-' + i,
        name: a.n, icon: a.i, tone: a.tn, tagline: render(a.t, ctx),
        why: render(a.w, ctx),
        guide: guide,
        keywords: a.k.slice(0),
        samples: samples
      });
    }
    return out;
  }

